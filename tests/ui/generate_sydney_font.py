"""Generate 4-bpp SYDNEY digits directly from the bundled vector font.

Only '-' and '0' through '9' are included. Run manually after changing the asset.
Source: https://github.com/google/fonts/tree/main/ofl/barlowcondensed
Copyright 2017 The Barlow Project Authors. SIL OFL 1.1: assets/OFL.txt.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
font = ImageFont.truetype(str(Path(__file__).parent / "assets/BarlowCondensed-SemiBold.ttf"), 112 * 4)
bounds = font.getbbox("0")
cell_width = round(font.getlength("0"))
cell_height = bounds[3] - bounds[1] + 8
packed = bytearray()
descriptors = ["    {0},"]
for char in "-0123456789":
    cell = Image.new("L", (cell_width, cell_height))
    ImageDraw.Draw(cell).text((0, 4 - bounds[1]), char, font=font, fill=255)
    cell = cell.resize((44, 80), Image.Resampling.LANCZOS)
    values = [(pixel * 15 + 127) // 255 for pixel in cell.tobytes()]
    descriptors.append(f"    {{.bitmap_index = {len(packed)}, .adv_w = 784, .box_w = 44, .box_h = 80}}, /* {char} */")
    packed.extend((values[index] << 4) | values[index + 1] for index in range(0, len(values), 2))

lines = ["    " + ", ".join(f"0x{value:02x}" for value in packed[index:index + 16]) + ","
         for index in range(0, len(packed), 16)]
result = """/* SYDNEY 44x80 digits, Barlow Condensed SemiBold, SIL OFL 1.1.
 * Copyright 2017 The Barlow Project Authors (https://github.com/jpt/barlow).
 * License: tests/ui/assets/OFL.txt.
 * Generated by tests/ui/generate_sydney_font.py; 4 bpp, no runtime scaling. */
#include "lvgl.h"

static const uint8_t glyph_bitmap[] =
{
""" + "\n".join(lines) + """
};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] =
{
""" + "\n".join(descriptors) + """
};

static const lv_font_fmt_txt_cmap_t cmaps[] =
{
    {.range_start = 45, .range_length = 1, .glyph_id_start = 1, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},
    {.range_start = 48, .range_length = 10, .glyph_id_start = 2, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}
};

static lv_font_fmt_txt_glyph_cache_t cache;
static const lv_font_fmt_txt_dsc_t font_dsc =
{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .cmap_num = 2,
    .bpp = 4,
    .cache = &cache
};

const lv_font_t ui_sydney_digits =
{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 80,
    .base_line = 0,
    .dsc = &font_dsc
};
"""
assert len(packed) == 11 * 44 * 80 // 2
(ROOT / "application/ui_sydney_font.c").write_text(result, encoding="utf-8", newline="\r\n")
print(f"SYDNEY font: {len(packed)} bitmap bytes, 11 glyphs")
