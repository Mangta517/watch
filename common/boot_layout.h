#ifndef BOOT_LAYOUT_H
#define BOOT_LAYOUT_H

/* sector 0..1主引导，2..3独立保底，4..6手表APP，7电压/复位/步数日志。 */
#define BOOTLOADER_START_ADDR          0x08000000
#define RECOVERY_START_ADDR            0x08008000
#define APP_START_ADDR                 0x08010000
#define APP_FLASH_END_ADDR             0x08060000
#define APP_MAX_SIZE                   (APP_FLASH_END_ADDR - APP_START_ADDR)
#define BOOT_VECTOR_BYTES              0x198 /* STM32F411xE启动汇编的完整向量表。 */
#define BOOT_APP_MIN_SIZE              (BOOT_VECTOR_BYTES + 2)
#define BOOT_APP_MIN_MSP               0x20000400
#define BOOT_SRAM_END                  0x20020000
#define BOOTLOADER_EEPROM_FLAG_ADDR    0xC0
#define BOOTLOADER_FLAG_UPDATING       0x5A
#define BOOTLOADER_FLAG_VALID          0xA5

/* sector 7日志记录与升级边界统一定义，禁止APP擦写越过该分区。 */
#define BATTERY_LOG_START_ADDR   APP_FLASH_END_ADDR
#define BATTERY_LOG_END_ADDR     0x08080000
#define BATTERY_LOG_RECORD_BYTES 8
#define STEP_LOG_START_ADDR      0x0807E000
#define BATTERY_LOG_CAPACITY     ((STEP_LOG_START_ADDR - BATTERY_LOG_START_ADDR) / BATTERY_LOG_RECORD_BYTES)
#define BATTERY_LOG_LEGACY_CAPACITY ((BATTERY_LOG_END_ADDR - BATTERY_LOG_START_ADDR) / BATTERY_LOG_RECORD_BYTES)
/* 首槽为布局标记，其余1023槽为steps/day/CRC提交记录。 */
#define STEP_LOG_FIRST_SLOT      BATTERY_LOG_CAPACITY
#define STEP_LOG_CAPACITY        (BATTERY_LOG_LEGACY_CAPACITY - STEP_LOG_FIRST_SLOT - 1)

#endif
